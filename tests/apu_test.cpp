// 테스트를 위한 픽스처 클래스
class APURegisterTest
	: public ::testing::TestWithParam<std::tuple<uint16_t, uint8_t, uint8_t>> {
  protected:
	SystemClock clock;
	APU apu;

	APURegisterTest() : apu(clock) {}

	void SetUp() override { apu.reset(); }
};

TEST_P(APURegisterTest, WriteAndRead) {
	auto [addr, write_val, expected_val] = GetParam();

	apu.register_write(addr, write_val);
	uint8_t actual_val = apu.register_read(addr);

	EXPECT_EQ(actual_val, expected_val)
		<< "Failed at address 0x" << std::hex << (int)addr
		<< " after writing 0x" << (int)write_val;
}

